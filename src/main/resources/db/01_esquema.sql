-- =====================================================================
-- Peru de Estacion - Esquema de base de datos (PostgreSQL / Supabase)
-- Ejecutar UNA vez en Supabase > SQL Editor > New query > Run.
-- Crea las 14 tablas del modelo de datos con sus restricciones.
-- =====================================================================

CREATE TABLE departamento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(3)  NOT NULL UNIQUE,
    nombre          VARCHAR(60) NOT NULL,
    region_natural  VARCHAR(10) NOT NULL CHECK (region_natural IN ('COSTA', 'SIERRA', 'SELVA'))
);

CREATE TABLE alimento (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(80)  NOT NULL UNIQUE,
    categoria    VARCHAR(10)  NOT NULL CHECK (categoria IN ('FRUTA', 'VERDURA', 'TUBERCULO', 'PESCADO')),
    descripcion  VARCHAR(500),
    imagen_url   VARCHAR(300)
);

-- Tabla central: nivel de oferta de cada alimento por departamento y mes (regla RN01).
CREATE TABLE temporada (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alimento_id      BIGINT     NOT NULL REFERENCES alimento (id),
    departamento_id  BIGINT     NOT NULL REFERENCES departamento (id),
    mes              INTEGER    NOT NULL CHECK (mes BETWEEN 1 AND 12),
    nivel            VARCHAR(5) NOT NULL CHECK (nivel IN ('ALTA', 'MEDIA', 'BAJA')),
    CONSTRAINT uq_temporada UNIQUE (alimento_id, departamento_id, mes)
);

CREATE TABLE precio_referencia (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alimento_id      BIGINT         NOT NULL REFERENCES alimento (id),
    departamento_id  BIGINT         NOT NULL REFERENCES departamento (id),
    precio_kg        NUMERIC(10, 2) NOT NULL CHECK (precio_kg > 0),
    fecha            DATE           NOT NULL,
    fuente           VARCHAR(120)   NOT NULL
);

CREATE TABLE consejo_conservacion (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alimento_id    BIGINT       NOT NULL REFERENCES alimento (id) ON DELETE CASCADE,
    metodo         VARCHAR(60)  NOT NULL,
    descripcion    VARCHAR(500) NOT NULL,
    duracion_dias  INTEGER CHECK (duracion_dias > 0)
);

CREATE TABLE alerta_nino (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comunicado  VARCHAR(40) NOT NULL,
    fecha       DATE        NOT NULL,
    estado      VARCHAR(40) NOT NULL,
    magnitud    VARCHAR(40) NOT NULL,
    vigente     BOOLEAN     NOT NULL DEFAULT FALSE
);
-- Regla RN02: solo una alerta vigente a la vez (la base de datos tambien lo garantiza).
CREATE UNIQUE INDEX uq_alerta_vigente ON alerta_nino (vigente) WHERE vigente;

CREATE TABLE impacto_region (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alerta_id        BIGINT      NOT NULL REFERENCES alerta_nino (id) ON DELETE CASCADE,
    departamento_id  BIGINT      NOT NULL REFERENCES departamento (id),
    sector           VARCHAR(60) NOT NULL,
    nivel_riesgo     VARCHAR(5)  NOT NULL CHECK (nivel_riesgo IN ('ALTO', 'MEDIO', 'BAJO')),
    descripcion      VARCHAR(500)
);

CREATE TABLE impacto_alimento (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    impacto_id   BIGINT     NOT NULL REFERENCES impacto_region (id) ON DELETE CASCADE,
    alimento_id  BIGINT     NOT NULL REFERENCES alimento (id),
    riesgo_alza  VARCHAR(5) NOT NULL CHECK (riesgo_alza IN ('ALTO', 'MEDIO', 'BAJO')),
    CONSTRAINT uq_impacto_alimento UNIQUE (impacto_id, alimento_id)
);

CREATE TABLE programa_apoyo (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(120) NOT NULL UNIQUE,
    entidad         VARCHAR(120) NOT NULL,
    url_oficial     VARCHAR(300) NOT NULL,
    fecha_revision  DATE         NOT NULL
);

CREATE TABLE requisito (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programa_id  BIGINT       NOT NULL REFERENCES programa_apoyo (id) ON DELETE CASCADE,
    descripcion  VARCHAR(300) NOT NULL,
    orden        INTEGER      NOT NULL
);

CREATE TABLE centro_apoyo (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programa_id      BIGINT       NOT NULL REFERENCES programa_apoyo (id),
    departamento_id  BIGINT       NOT NULL REFERENCES departamento (id),
    nombre           VARCHAR(120) NOT NULL,
    direccion        VARCHAR(200) NOT NULL,
    distrito         VARCHAR(80)  NOT NULL,
    telefono         VARCHAR(20)
);

-- Simulaciones anonimas: no se guarda nombre, DNI ni direccion (regla RN04).
CREATE TABLE simulacion (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departamento_id      BIGINT         NOT NULL REFERENCES departamento (id),
    adultos              INTEGER        NOT NULL CHECK (adultos >= 0),
    ninos                INTEGER        NOT NULL CHECK (ninos >= 0),
    adultos_mayores      INTEGER        NOT NULL CHECK (adultos_mayores >= 0),
    dias                 INTEGER        NOT NULL CHECK (dias >= 3),
    tipo_vivienda        VARCHAR(15)    NOT NULL,
    capacidad_economica  VARCHAR(5)     NOT NULL,
    kcal_total           INTEGER        NOT NULL,
    costo_estimado       NUMERIC(10, 2) NOT NULL,
    creado_en            TIMESTAMP      NOT NULL DEFAULT now()
);

CREATE TABLE parametro_simulador (
    clave        VARCHAR(40) PRIMARY KEY,
    valor        NUMERIC(12, 4) NOT NULL CHECK (valor >= 0),
    descripcion  VARCHAR(200)
);

CREATE TABLE usuario_admin (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(120) NOT NULL UNIQUE,
    password_hash  VARCHAR(100) NOT NULL,
    rol            VARCHAR(20)  NOT NULL DEFAULT 'ADMIN',
    activo         BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Indices para las consultas mas frecuentes.
CREATE INDEX ix_temporada_dep_mes ON temporada (departamento_id, mes);
CREATE INDEX ix_precio_alimento_dep_fecha ON precio_referencia (alimento_id, departamento_id, fecha DESC);
CREATE INDEX ix_centro_dep ON centro_apoyo (departamento_id);

-- =====================================================================
-- Seguridad en Supabase: se habilita RLS sin politicas en todas las tablas.
-- Asi la Data API publica de Supabase (con la clave anon/publishable) NO puede leerlas.
-- El backend Spring Boot se conecta con el rol postgres, que tiene BYPASSRLS,
-- por lo que la autorizacion real la hace Spring Security.
-- =====================================================================
ALTER TABLE departamento         ENABLE ROW LEVEL SECURITY;
ALTER TABLE alimento             ENABLE ROW LEVEL SECURITY;
ALTER TABLE temporada            ENABLE ROW LEVEL SECURITY;
ALTER TABLE precio_referencia    ENABLE ROW LEVEL SECURITY;
ALTER TABLE consejo_conservacion ENABLE ROW LEVEL SECURITY;
ALTER TABLE alerta_nino          ENABLE ROW LEVEL SECURITY;
ALTER TABLE impacto_region       ENABLE ROW LEVEL SECURITY;
ALTER TABLE impacto_alimento     ENABLE ROW LEVEL SECURITY;
ALTER TABLE programa_apoyo       ENABLE ROW LEVEL SECURITY;
ALTER TABLE requisito            ENABLE ROW LEVEL SECURITY;
ALTER TABLE centro_apoyo         ENABLE ROW LEVEL SECURITY;
ALTER TABLE simulacion           ENABLE ROW LEVEL SECURITY;
ALTER TABLE parametro_simulador  ENABLE ROW LEVEL SECURITY;
ALTER TABLE usuario_admin        ENABLE ROW LEVEL SECURITY;
